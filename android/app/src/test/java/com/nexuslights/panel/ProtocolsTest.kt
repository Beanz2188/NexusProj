/**
 * Vectors are the Python test suite's, plus bytes generated by running the
 * air-bridge branch's nexuslights/protocols on sample inputs, so the two
 * implementations can't drift apart.
 */
class ProtocolsTest {
    private fun b(vararg v: Int) = ByteArray(v.size) { v[it].toByte() }
    private fun hex(s: String) = ByteArray(s.length / 2) { s.substring(it * 2, it * 2 + 2).toInt(16).toByte() }

    // ---- from tests/test_protocols.py --------------------------------------

    @Test fun trionesPowerFrames() {
        assertArrayEquals(b(0xCC, 0x23, 0x33), Triones().powerOn())
        assertArrayEquals(b(0xCC, 0x24, 0x33), Triones().powerOff())
    }

    @Test fun trionesRgbClamps() {
        assertArrayEquals(b(0x56, 255, 0, 128, 0x00, 0xF0, 0xAA), Triones().setRgb(300, -10, 128))
    }

    @Test fun trionesWhiteScales() {
        assertArrayEquals(b(0x56, 0, 0, 0, 255, 0x0F, 0xAA), Triones().setWhite(100))
        assertArrayEquals(b(0x56, 0, 0, 0, 0, 0x0F, 0xAA), Triones().setWhite(0))
    }

    @Test fun elkPowerFrames() {
        assertArrayEquals(b(0x7E, 0x00, 0x04, 0xF0, 0x00, 0x01, 0xFF, 0x00, 0xEF), ElkBledom().powerOn())
        assertArrayEquals(b(0x7E, 0x00, 0x04, 0x00, 0x00, 0x00, 0xFF, 0x00, 0xEF), ElkBledom().powerOff())
    }

    @Test fun elkRgb() {
        assertArrayEquals(b(0x7E, 0x00, 0x05, 0x03, 1, 2, 3, 0x00, 0xEF), ElkBledom().setRgb(1, 2, 3))
    }

    @Test fun elkBrightnessClamped() {
        assertArrayEquals(b(0x7E, 0x00, 0x01, 100, 0xFF, 0xFF, 0xFF, 0x00, 0xEF), ElkBledom().setBrightness(150))
    }

    @Test fun iotwfPowerFramesMatchHardwareCapture() {
        val p = LedNetWfIotwf()
        assertArrayEquals(hex("000180000004050b71230fa3"), p.powerOn())
        assertArrayEquals(hex("000280000004050b71240fa4"), p.powerOff())
    }

    @Test fun iotwfRgbRed() {
        assertArrayEquals(hex("00018000000d0e0b3ba100646400000000000000a4"), LedNetWfIotwf().setRgb(255, 0, 0))
    }

    @Test fun registryAndGuessing() {
        for (id in listOf("triones", "elkbledom", "elkbledom-notify", "lednetwf", "lednetwf-iotwf", "vcblelight", "mrstar", "fluxled")) {
            assertEquals(id, LightProtocol.create(id).id)
        }
        val e = runCatching { LightProtocol.create("nope") }.exceptionOrNull()
        assertTrue(e?.message!!.contains("Unknown protocol"))
        assertEquals("triones", LightProtocol.guess("Triones-A1B2")?.id)
        assertEquals("elkbledom", LightProtocol.guess("ELK-BLEDOM")?.id)
        assertEquals("lednetwf-iotwf", LightProtocol.guess("IOTWF06B")?.id)
        assertEquals("mrstar", LightProtocol.guess("GATT--DEMO")?.id)
        assertEquals("vcblelight", LightProtocol.guess("VC-BLELIGHT")?.id)
        assertEquals("lednetwf", LightProtocol.guess("LEDnetWF02")?.id)
        assertNull(LightProtocol.guess("Some Random Device"))
        assertNull(LightProtocol.guess(null))
    }

    // ---- generated from the air-bridge Python protocols --------------------

    @Test fun lednetwfFrames() {
        val p = LedNetWf()
        assertArrayEquals(b(0x00, 0x00, 0x80, 0x00, 0x00, 0x0D, 0x0E, 0x0B, 0x3B, 0x23, 0, 0, 0, 0, 0, 0, 0, 0x32, 0, 0, 0x90), p.powerOn())
        assertArrayEquals(b(0x00, 0x00, 0x80, 0x00, 0x00, 0x0D, 0x0E, 0x0B, 0x3B, 0x24, 0, 0, 0, 0, 0, 0, 0, 0x32, 0, 0, 0x91), p.powerOff())
        assertArrayEquals(b(0x00, 0x00, 0x80, 0x00, 0x00, 0x0D, 0x0E, 0x0B, 0x3B, 0xA1, 0x3F, 0x5F, 0x4E, 0, 0, 0, 0, 0, 0, 0, 0xC8), p.setRgb(10, 200, 30))
        assertArrayEquals(b(0x00, 0x00, 0x80, 0x00, 0x00, 0x0D, 0x0E, 0x0B, 0x3B, 0xA1, 0x00, 0x00, 0x32, 0, 0, 0, 0, 0, 0, 0, 0x0E), p.setRgb(128, 128, 128))
        assertArrayEquals(b(0x00, 0x00, 0x80, 0x00, 0x00, 0x0D, 0x0E, 0x0B, 0x3B, 0xA1, 0x10, 0x64, 0x64, 0, 0, 0, 0, 0, 0, 0, 0xB4), p.setRgb(255, 140, 0))
        assertNull(p.setBrightness(50))
    }

    @Test fun iotwfSequenceCountsAcrossCommands() {
        val p = LedNetWfIotwf()
        p.powerOn(); p.powerOff() // seq 1, 2
        assertArrayEquals(
            b(0x00, 0x03, 0x80, 0x00, 0x00, 0x0D, 0x0E, 0x0B, 0x3B, 0xA1, 0x00, 0x64, 0x64, 0, 0, 0, 0, 0, 0, 0, 0xA4),
            p.setRgb(255, 0, 0),
        )
        assertArrayEquals(
            b(0x00, 0x04, 0x80, 0x00, 0x00, 0x0D, 0x0E, 0x0B, 0x3B, 0xA1, 0x3F, 0x5F, 0x4E, 0, 0, 0, 0, 0, 0, 0, 0xC8),
            p.setRgb(10, 200, 30),
        )
        repeat(251) { p.powerOn() } // seq 5..255
        assertEquals(1, p.powerOn()[1].toInt()) // wraps 255 -> 1
    }

    @Test fun elkNotifyVariant() {
        val p = ElkBledomNotify()
        assertEquals("0000fff4-0000-1000-8000-00805f9b34fb", p.notifyCharacteristic.toString())
        assertTrue(p.writeWithResponse)
        assertArrayEquals(ElkBledom().setRgb(255, 140, 0), p.setRgb(255, 140, 0))
        assertArrayEquals(b(0x7E, 0x00, 0x01, 0x25, 0xFF, 0xFF, 0xFF, 0x00, 0xEF), p.setBrightness(37))
    }

    @Test fun vcBleLight() {
        val p = VcBleLight()
        assertArrayEquals(b(0x01, 0x01), p.powerOn())
        assertArrayEquals(b(0x01, 0x00), p.powerOff())
        assertArrayEquals(b(0x03, 0xFF, 0x8C, 0x00, 0, 0, 0), p.setRgb(255, 140, 0))
        assertArrayEquals(b(0x02, 0x25), p.setBrightness(37))
    }

    @Test fun mrStar() {
        val p = MrStar()
        assertTrue(p.powerOffDisconnects); assertTrue(p.writeWithResponse); assertFalse(p.colorIncludesBrightness)
        assertArrayEquals(b(0xBC, 0x01, 0x01, 0x01, 0x55), p.powerOn())
        assertArrayEquals(b(0xBC, 0x01, 0x01, 0x00, 0x55), p.powerOff())
        assertArrayEquals(b(0xBC, 0x04, 0x06, 0x00, 0x00, 0x03, 0xE8, 0x00, 0x00, 0x55), p.setRgb(255, 0, 0))
        assertArrayEquals(b(0xBC, 0x04, 0x06, 0x00, 0x7E, 0x03, 0xB6, 0x00, 0x00, 0x55), p.setRgb(10, 200, 30))
        assertArrayEquals(b(0xBC, 0x04, 0x06, 0x00, 0x20, 0x03, 0xE8, 0x00, 0x00, 0x55), p.setRgb(255, 140, 0))
        assertArrayEquals(b(0xBC, 0x05, 0x06, 0x00, 0x00, 0, 0, 0, 0, 0x55), p.setBrightness(0))
        assertArrayEquals(b(0xBC, 0x05, 0x06, 0x01, 0x72, 0, 0, 0, 0, 0x55), p.setBrightness(37))
        assertArrayEquals(b(0xBC, 0x05, 0x06, 0x03, 0xE8, 0, 0, 0, 0, 0x55), p.setBrightness(100))
    }

    /** Matches flux_led 1.2.0 ProtocolLEDENET8Byte output. */
    @Test fun fluxLedDimmer() {
        val p = FluxLed()
        assertArrayEquals(hex("818a8b96"), p.stateQuery())
        assertArrayEquals(hex("71230fa3"), p.powerOn())
        assertArrayEquals(hex("71240fa4"), p.powerOff())
        assertArrayEquals(hex("31000000000f0f4f"), p.setBrightness(0))
        assertArrayEquals(hex("31000000ff0f0f4e"), p.setBrightness(100))
        assertArrayEquals(hex("31ff008000f00faf"), p.setRgb(255, 0, 128))
        assertFalse(p.supportsColor)
        assertEquals(LightProtocol.Transport.WIFI, p.transport)
    }

    @Test fun uuids() {
        assertEquals("0000ffd9-0000-1000-8000-00805f9b34fb", Triones().writeCharacteristic.toString())
        assertEquals("0000fff3-0000-1000-8000-00805f9b34fb", ElkBledom().writeCharacteristic.toString())
        assertEquals("0000ae01-0000-1000-8000-00805f9b34fb", VcBleLight().writeCharacteristic.toString())
        assertEquals("0000ff01-0000-1000-8000-00805f9b34fb", LedNetWf().writeCharacteristic.toString())
    }

    @Test fun hsv() {
        assertEquals(Triple(255, 0, 0), ColorMath.hsvToRgb(0f, 1f, 1f))
        assertEquals(Triple(0, 255, 0), ColorMath.hsvToRgb(120f, 1f, 1f))
        assertEquals(Triple(128, 128, 128), ColorMath.hsvToRgb(200f, 0f, 0.5f))
    }
}

class ConfigImportTest {
    @Test fun parsesNexusLightsYaml() {
        val yaml = """
            lights:
            - address: aa:bb:cc:dd:ee:ff
              name: Desk Strip
              protocol: triones
              on_demand: false
            - address: '11:22:33:44:55:66'
              name: "Kitchen"
              protocol: lednetwf-iotwf
              on_demand: true
            - address: 192.168.70.50
              name: Hallway
              protocol: fluxled
            - address: 99:99:99:99:99:99
              name: Unknown proto
              protocol: nope
            apple_tv:
              identifier: ABC
              companion_credentials: secret
        """.trimIndent()
        val out = ConfigImport.parseLightsYaml(yaml)
        assertEquals(3, out.size)
        assertEquals("AA:BB:CC:DD:EE:FF", out[0].address)
        assertEquals("Desk Strip", out[0].name)
        assertEquals("triones", out[0].protocol)
        assertFalse(out[0].onDemand)
        assertEquals("11:22:33:44:55:66", out[1].address)
        assertEquals("lednetwf-iotwf", out[1].protocol)
        assertTrue(out[1].onDemand)
        assertEquals("192.168.70.50", out[2].address)
        assertEquals("fluxled", out[2].protocol)
    }
}
